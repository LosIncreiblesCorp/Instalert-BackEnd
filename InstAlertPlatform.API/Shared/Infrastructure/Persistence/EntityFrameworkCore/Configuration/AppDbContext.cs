{
    protected override void ConfigureConventions(ModelConfigurationBuilder builder) => builder.Properties<DateTimeOffset>().HaveConversion<UtcTimestampConverter>();
    protected override void OnModelCreating(ModelBuilder builder)
    {
        base.OnModelCreating(builder);
        builder.Entity<AlertRecord>().ToTable("alerts");
        builder.Entity<AlertRecord>().Property(x => x.BusinessId).HasMaxLength(80);
        builder.Entity<AlertRecord>().Property(x => x.EmployeeId).HasMaxLength(80);
        builder.Entity<AlertRecord>().Property(x => x.Kind).HasMaxLength(30);
        builder.Entity<AlertRecord>().Property(x => x.Status).HasMaxLength(30);
        builder.Entity<AlertRecord>().Property(x => x.ReportStatus).HasMaxLength(20);
        builder.Entity<AlertRecord>().Property(x => x.Category).HasMaxLength(80);
        builder.Entity<AlertRecord>().Property(x => x.Description).HasMaxLength(2000);
        builder.Entity<AlertRecord>().Property(x => x.Location).HasMaxLength(250);
        builder.Entity<AlertRecord>().HasIndex(x => new { x.BusinessId, x.Status });
        builder.Entity<AlertRecord>().HasIndex(x => x.EmployeeId);
        builder.ApplyMappingConfiguration();
        builder.ApplyNotificationsConfiguration();
        builder.Entity<Report>().ToTable("dashboard_reports");
        builder.Entity<Report>().Property(x => x.BusinessId).HasMaxLength(80).IsRequired();
        builder.Entity<Report>().Property(x => x.StartDate).HasColumnType("date");
        builder.Entity<Report>().Property(x => x.EndDate).HasColumnType("date");
        builder.Entity<Report>().Property(x => x.SummaryJson).HasColumnType("longtext").IsRequired();
        builder.Entity<Report>().Property(x => x.GenerationSource).HasMaxLength(20).IsRequired();
        builder.Entity<Report>().Property(x => x.GeneratedByUserId).HasMaxLength(160);
        builder.Entity<Report>().HasIndex(x => new { x.BusinessId, x.GeneratedAt }).HasDatabaseName("i_x_dashboard_reports_business_id_generated_at");
        builder.Entity<AlertPreferences>().ToTable("alert_preferences");
        builder.Entity<BusinessProfile>().ToTable("business_profiles");
        builder.Entity<BusinessProfile>().HasKey(x => x.Id);
        builder.Entity<BusinessProfile>().Property(x => x.Id).ValueGeneratedOnAdd();
        builder.Entity<BusinessProfile>().Property(x => x.OwnerUserId).HasMaxLength(160);
        builder.Entity<BusinessProfile>().Property(x => x.Version).HasMaxLength(36).IsConcurrencyToken();
        builder.Entity<BusinessProfile>().HasIndex(x => x.OwnerUserId);
        builder.Entity<BusinessProfile>().Property(x => x.SeatRevision).HasDefaultValue(0L);
        builder.Entity<BusinessProfile>().Property(x => x.TaxId).HasConversion(value => value.Value, value => new TaxIdentifier(value)).HasMaxLength(11);
        builder.Entity<BusinessProfile>().HasIndex(x => x.TaxId).IsUnique();
        builder.Entity<BusinessProfile>().Property(x => x.Name).HasMaxLength(150);
        builder.Entity<BusinessProfile>().Property(x => x.Address).HasMaxLength(250);
        builder.Entity<BusinessMember>().ToTable("business_members");
        builder.Entity<BusinessMember>().Property(x => x.BusinessId).IsRequired();
        builder.Entity<BusinessMember>().Property(x => x.UserId).HasMaxLength(160);
        builder.Entity<BusinessMember>().Property(x => x.DisplayName).HasMaxLength(100);
        builder.Entity<BusinessMember>().Property(x => x.Email).HasMaxLength(254);
        builder.Entity<BusinessMember>().Property(x => x.Role).HasMaxLength(30);
        builder.Entity<BusinessMember>().Property(x => x.Status).HasMaxLength(20);
        builder.Entity<BusinessMember>().HasIndex(x => new { x.BusinessId, x.UserId }).IsUnique();
        builder.Entity<BusinessMember>().HasIndex(x => new { x.BusinessId, x.Email }).IsUnique();
        builder.Entity<BusinessMember>().HasIndex(x => new { x.BusinessId, x.Status }).HasDatabaseName("i_x_business_members_business_id_status");
        builder.Entity<BusinessMember>().HasIndex(x => new { x.UserId, x.Status }).HasDatabaseName("i_x_business_members_user_id_status");
        builder.Entity<BusinessMember>().HasOne<BusinessProfile>().WithMany().HasForeignKey(x => x.BusinessId).OnDelete(DeleteBehavior.Restrict).HasConstraintName("f_k_business_members__business_profile_business_id");
        builder.Entity<StaffInvitation>().ToTable("staff_invitations");
        builder.Entity<StaffInvitation>().Property(x => x.BusinessId).IsRequired();
        builder.Entity<StaffInvitation>().Property(x => x.DisplayName).HasMaxLength(100);
        builder.Entity<StaffInvitation>().Property(x => x.Email).HasMaxLength(254);
        builder.Entity<StaffInvitation>().Property(x => x.Status).HasMaxLength(20);
        builder.Entity<StaffInvitation>().HasIndex(x => new { x.BusinessId, x.Status });
        builder.Entity<StaffInvitation>().HasOne<BusinessProfile>().WithMany().HasForeignKey(x => x.BusinessId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<EmergencyContact>().ToTable("emergency_contacts");
        builder.Entity<EmergencyContact>().Property(c => c.EmployeeId).HasMaxLength(80).IsRequired();
        builder.Entity<EmergencyContact>().HasIndex(c => c.EmployeeId);
        builder.Entity<EmergencyContact>().Property(c => c.FullName).HasMaxLength(100).IsRequired();
        builder.Entity<EmergencyContact>().Property(c => c.Relationship).HasMaxLength(60).IsRequired();
        builder.Entity<EmergencyContact>().Property(c => c.Phone).HasMaxLength(16).IsRequired();
        builder.Entity<EmergencyContact>().Property(c => c.Email).HasMaxLength(254);
        builder.Entity<EmergencyContact>().Property(c => c.Notes).HasMaxLength(140);
        builder.Entity<PayPalWebhookReceipt>().ToTable("paypal_webhook_receipts");
        builder.Entity<PayPalWebhookReceipt>().Property(x => x.EventType).HasMaxLength(100);
        builder.Entity<Plan>().ToTable("plans");
        builder.Entity<Plan>().Property(x => x.Name).HasMaxLength(100);
        builder.Entity<Plan>().Property(x => x.Price).HasPrecision(10, 2);
        builder.Entity<Plan>().Property(x => x.Currency).HasMaxLength(3);
        builder.Entity<Plan>().Property(x => x.BillingCycle).HasMaxLength(10);
        builder.Entity<Plan>().Property(x => x.ProviderPlanId).HasMaxLength(100);
        builder.Entity<Plan>().HasIndex(x => x.ProviderPlanId).IsUnique();
        builder.Entity<Plan>().HasData(new { Id = "essential", Version = "catalog-v1", CreatedAt = (DateTimeOffset? )null, UpdatedAt = (DateTimeOffset? )null, Name = "Essential", Price = 15m, Currency = "USD", BillingCycle = "monthly", MaxEmployees = 4, ProviderPlanId = "P-9G467950ML2745201NLOCKGI" }, new { Id = "professional", Version = "catalog-v1", CreatedAt = (DateTimeOffset? )null, UpdatedAt = (DateTimeOffset? )null, Name = "Professional", Price = 30m, Currency = "USD", BillingCycle = "monthly", MaxEmployees = 8, ProviderPlanId = "P-66N5798614080793BNLOCKNY" }, new { Id = "business", Version = "catalog-v1", CreatedAt = (DateTimeOffset? )null, UpdatedAt = (DateTimeOffset? )null, Name = "Business", Price = 45m, Currency = "USD", BillingCycle = "monthly", MaxEmployees = 15, ProviderPlanId = "P-8D911646UD924981MNLOCK6Q" });
        builder.Entity<Subscription>().ToTable("subscriptions");
        builder.Entity<Subscription>().Property(x => x.BusinessId).HasMaxLength(80);
        builder.Entity<Subscription>().Property(x => x.PlanId).HasMaxLength(80);
        builder.Entity<Subscription>().Property(x => x.ProviderSubscriptionId).HasMaxLength(100);
        builder.Entity<Subscription>().Property(x => x.Status).HasMaxLength(20);
        builder.Entity<Subscription>().HasIndex(x => x.BusinessId).IsUnique();
        builder.Entity<Subscription>().HasIndex(x => x.ProviderSubscriptionId).IsUnique();
        builder.Entity<Subscription>().HasIndex(x => x.PlanId).HasDatabaseName("i_x_subscriptions_plan_id");
        builder.Entity<Subscription>().HasOne<Plan>().WithMany().HasForeignKey(x => x.PlanId).OnDelete(DeleteBehavior.Restrict).HasConstraintName("f_k_subscriptions_plans_plan_id");
        builder.Entity<CheckoutIntent>().ToTable("checkout_intents");
        builder.Entity<CheckoutIntent>().Property(x => x.BusinessId).HasMaxLength(80);
        builder.Entity<CheckoutIntent>().Property(x => x.PlanId).HasMaxLength(80);
        builder.Entity<CheckoutIntent>().HasIndex(x => new { x.BusinessId, x.Completed, x.ExpiresAt }).HasDatabaseName("i_x_checkout_intents_business_id_completed_expires_at");
        builder.Entity<CheckoutIntent>().HasIndex(x => x.PlanId).HasDatabaseName("i_x_checkout_intents_plan_id");
        builder.Entity<CheckoutIntent>().HasOne<Plan>().WithMany().HasForeignKey(x => x.PlanId).OnDelete(DeleteBehavior.Restrict).HasConstraintName("f_k_checkout_intents_plans_plan_id");
        builder.Entity<PaymentTransaction>().ToTable("payment_transactions");
        builder.Entity<PaymentTransaction>().Property(x => x.BusinessId).HasMaxLength(80);
        builder.Entity<PaymentTransaction>().Property(x => x.ProviderTransactionId).HasMaxLength(100);
        builder.Entity<PaymentTransaction>().HasIndex(x => x.ProviderTransactionId).IsUnique();
        builder.Entity<PaymentTransaction>().HasIndex(x => new { x.BusinessId, x.PaidAt }).HasDatabaseName("i_x_payment_transactions_business_id_paid_at");
        builder.Entity<PaymentTransaction>().Property(x => x.Amount).HasPrecision(10, 2);
        builder.Entity<PaymentTransaction>().Property(x => x.Currency).HasMaxLength(3);
        builder.Entity<UserProfile>().ToTable("profiles");
        builder.Entity<UserProfile>().Property(p => p.FirstName).HasMaxLength(100).IsRequired();
        builder.Entity<UserProfile>().Property(p => p.LastName).HasMaxLength(100).IsRequired();
        builder.Entity<UserProfile>().Property(p => p.Dni).HasConversion(value => value.Value, value => new NationalIdentityNumber(value)).HasMaxLength(8).IsRequired();
        builder.Entity<UserProfile>().Property(p => p.Phone).HasMaxLength(16);
        builder.Entity<UserPreferences>().ToTable("user_preferences");
        builder.Entity<UserPreferences>().Property(p => p.Locale).HasConversion(value => value.Value, value => new ApplicationLocale(value)).HasMaxLength(6).IsRequired();
        builder.Entity<OutboxMessage>().ToTable("outbox_messages");
        builder.Entity<OutboxMessage>().Property(x => x.EventType).HasMaxLength(100);
        builder.Entity<OutboxMessage>().Property(x => x.Payload).HasColumnType("longtext");
        builder.Entity<OutboxMessage>().HasIndex(x => x.ProcessedAt);
        foreach (var entity in builder.Model.GetEntityTypes().Where(x => typeof(AuditedEntity).IsAssignableFrom(x.ClrType)))
        {
            builder.Entity(entity.ClrType).HasKey(nameof(AuditedEntity.Id));
            builder.Entity(entity.ClrType).Property(nameof(AuditedEntity.Id)).HasMaxLength(160);
            builder.Entity(entity.ClrType).Property(nameof(AuditedEntity.Version)).HasMaxLength(36).IsConcurrencyToken();
        }

        builder.Entity<UserProfile>().Property(x => x.Id).HasMaxLength(80);
        builder.Entity<Plan>().Property(x => x.Id).HasMaxLength(80);
        builder.Entity<OutboxMessage>().Property(x => x.Id).HasMaxLength(255);
        builder.Entity<OutboxMessage>().Property(x => x.Version).HasColumnType("longtext");

        builder.UseSnakeCaseNamingConvention();
    }
}
